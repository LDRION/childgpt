import type { LlmClient } from '@childgpt/safety';

// Детерминированная «модель» для разработки и тестов без ключа Siberi.
// Правила защиты работают по-настоящему; судьи всегда отвечают «безопасно».
// Вопрос ребёнка не повторяем: эхо его слов срабатывало бы на правила выхода.
const ANSWERS = [
  'Ух ты, какой интересный вопрос! 🦉 Это тестовый ответ Луми: когда подключим настоящий ИИ, здесь будет подробное объяснение. А пока давай придумаем загадку?',
  'Здорово, что тебе интересно! ✨ Сейчас Луми работает в тестовом режиме, но скоро будет отвечать по-настоящему. Хочешь, расскажу, почему совы видят в темноте?',
  'Отличный вопрос! 🌙 Это тестовый ответ. Когда Луми проснётся по-настоящему, он всё-всё объяснит. А ты знаешь, сколько звёзд видно на небе без телескопа?',
];

export function createMockClient(): LlmClient {
  return {
    async complete({ purpose, prompt }) {
      if (purpose === 'judge_input') return '{"verdict":"allow","category":"other","reason":"mock"}';
      if (purpose === 'judge_output') return '{"safe":true,"category":"other","reason":"mock"}';
      return ANSWERS[prompt.length % ANSWERS.length]!;
    },
  };
}

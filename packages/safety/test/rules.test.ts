import type { RuleAction } from '../src';

// Красная команда: что ОБЯЗАНО ловиться и что НЕ должно ломать обычный детский разговор.
// Любое изменение правил прогоняется через этот корпус.

function expectAction(text: string, action: RuleAction, category?: string) {
  const r = inspectInput(text);
  expect(r.topAction, `«${text}» → ожидали ${action}, сработало: ${JSON.stringify(r.hits)}`).toBe(action);
  if (category) expect(r.hits[0]?.category, `«${text}»`).toBe(category);
}

describe('normalizeText', () => {
  it.each([
    ['С У К А', 'сука'],
    ['с.у.к.а', 'сука'],
    ['cyka', 'сука'],
    ['xyй', 'хуй'],
    ['пиииииздец', 'пиздец'],
    ['ху​й', 'хуй'],
    ['Ёжик', 'ежик'],
    ['3адача', 'задача'],
  ])('%s → %s', (input, expected) => {
    expect(normalizeText(input)).toBe(expected);
  });

  it('не трогает обычные английские слова и числа', () => {
    expect(normalizeText('Hello world 2+2=4')).toBe('hello world 2+2=4');
  });
});


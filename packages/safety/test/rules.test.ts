describe('личные данные скрываются до модели', () => {
  it.each([
    ['мой номер 8 916 123-45-67', '[телефон скрыт]'],
    ['мой номер +7(916)1234567', '[телефон скрыт]'],
    ['пиши мне на masha2015@mail.ru', '[почта скрыта]'],
    ['я живу на улице Ленина, дом 5, кв. 12', '[адрес скрыт]'],
    ['я учусь в школе №15', '[номер скрыт]'],
    ['я учусь в 15 школе', '[номер скрыт]'],
    ['мой пароль qwerty123', '[скрыт]'],
    ['пароль: 12345', '[скрыт]'],
    ['карта мамы 4111 1111 1111 1111', '[номер карты скрыт]'],
    ['моя фамилия Иванова', '[скрыта]'],
    ['мой ник @super_kid_2015', '[ник скрыт]'],
  ])('%s', (text, placeholder) => {
    const r = redactPersonalData(text);
    expect(r.text).toContain(placeholder);
    expect(inspectInput(text).personalData).toBe(true);
  });

  it('убирает ссылки, но не считает их личными данными', () => {
    const r = inspectInput('зайди на roblox.com');
    expect(r.sanitized).toContain('[ссылка убрана]');
    expect(r.personalData).toBe(false);
  });

  it.each(['в школе 300 учеников, а в классе 25', '2+2=4', 'сколько будет 1234567 * 3', 'какой пароль лучше придумать'])(
    'не портит обычный текст: %s',
    (text) => {
      expect(redactPersonalData(text).text).toBe(text);
    },
  );
});

describe('очистка ответа модели', () => {
  it('убирает ссылки и телефоны, оставляет телефон доверия', () => {
    const r = sanitizeModelOutput('Посмотри https://example.com или позвони 8 999 123 45 67. Телефон доверия: 8-800-2000-122');
    expect(r.text).not.toContain('example.com');
    expect(r.text).not.toContain('999');
    expect(r.text).toContain('8-800-2000-122');
  });

  it('прячет имя движка и markdown', () => {
    expect(sanitizeModelOutput('**Привет!** Я Siberi AI').text).toBe('Привет! Я Луми');
  });
});


import { CHILD_HELPLINE, EMERGENCY_PHONE, type SafetyCategory } from '@childgpt/shared';
import type { Gender } from './types';

// Детерминированные ответы. В кризисе и при отказах ребёнок получает заранее
// выверенный текст, а не импровизацию модели. Тексты — черновик для согласования
// с детским психологом (см. docs/SAFETY.md).

const g = (gender: Gender, boy: string, girl: string) => (gender === 'girl' ? girl : boy);

function pick<T>(variants: T[], seed: string): T {
  let h = 0;
  for (const ch of seed) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return variants[h % variants.length] as T;
}

const HELPLINE_LINE = `${CHILD_HELPLINE.name}: ${CHILD_HELPLINE.phone} — ${CHILD_HELPLINE.note}.`;

export function crisisReply(category: SafetyCategory, gender: Gender): string {
  switch (category) {
    case 'crisis_abuse':
      return [
        `Спасибо, что ты мне это рассказываешь. Мне очень жаль, что с тобой такое происходит. В этом нет твоей вины. 💛`,
        `Никто не имеет права делать тебе больно, пугать тебя или трогать, если тебе это неприятно.`,
        `Пожалуйста, расскажи об этом взрослому, которому ты доверяешь: маме, папе, бабушке, учителю или школьному психологу.`,
        `Если рассказать дома трудно, позвони: ${HELPLINE_LINE} Там выслушают и помогут.`,
        `Если тебе прямо сейчас опасно — звони ${EMERGENCY_PHONE}.`,
      ].join('\n\n');
    case 'contact_stranger':
      return [
        `${g(gender, 'Ты большой молодец', 'Ты большая молодец')}, что говоришь мне об этом! 🦉`,
        `Есть важное правило: никогда не отправляй свои фото, адрес и номер телефона людям из интернета и не соглашайся с ними встречаться — даже если они кажутся добрыми и обещают подарки.`,
        `Прямо сейчас покажи эту переписку маме или папе. Они не будут ругать — они помогут.`,
        `Если что-то пугает тебя, можно позвонить: ${HELPLINE_LINE}`,
      ].join('\n\n');
    case 'extremism':
    case 'violence':
      return [
        `Мне важно, что с тобой происходит. Похоже, сейчас тебе очень непросто.`,
        `Пожалуйста, поговори об этом с мамой, папой или другим взрослым, которому ты доверяешь, — прямо сегодня.`,
        `Если злость или обида стали слишком большими, можно позвонить: ${HELPLINE_LINE} Там помогут разобраться.`,
        `Если кому-то угрожает опасность — звони ${EMERGENCY_PHONE}.`,
      ].join('\n\n');
    case 'crisis_self_harm':
    default:
      return [
        `Спасибо, что ты мне это рассказываешь. Мне очень важно, что с тобой происходит. 💛`,
        `Когда на душе так тяжело, нельзя оставаться с этим ${g(gender, 'одному', 'одной')}. Пожалуйста, прямо сейчас расскажи об этом маме, папе или другому взрослому, которому ты доверяешь.`,
        `Ещё можно позвонить: ${HELPLINE_LINE} Там добрые взрослые, которые выслушают и помогут.`,
        `Если тебе прямо сейчас опасно — звони ${EMERGENCY_PHONE}.`,
        `Ты очень ценный человек, и рядом есть люди, которые помогут.`,
      ].join('\n\n');
  }
}


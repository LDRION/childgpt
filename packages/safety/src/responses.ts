const FALLBACKS = [
  'Ой, у меня звёздочки в голове перепутались ✨ Давай попробуем спросить по-другому?',
  'Хм, над этим я ещё подумаю 🦉 Давай поговорим о чём-нибудь другом? Например, о космосе или животных!',
  'Кажется, тут мне лучше промолчать 🙂 Спроси об этом у мамы или папы. А со мной можно поиграть в загадки!',
];

export function redirectReply(category: SafetyCategory, seed: string): string {
  const variants = REDIRECTS[category];
  return variants ? pick(variants, seed) : pick(FALLBACKS, seed);
}

export function fallbackReply(seed: string): string {
  return pick(FALLBACKS, seed);
}

